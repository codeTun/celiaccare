import "server-only";

import { SESSION_IDLE_TIMEOUT_MS } from "@/lib/auth/routes";
import { getCurrentSessionId, requireAdmin } from "@/lib/auth/session";
import { decryptTotpSecret, formatTotpSecret, totpQrCodeSvg, totpUri } from "@/lib/auth/totp";
import { db } from "@/lib/prisma";

/* ==========================================================================
   READ — admin accounts & security (login, "Sécurité" page). Never cached.

   Two kinds of functions here:
   1. getAdminAuthByEmail / getAdminAuthById: INTERNAL records for the login
      and password checks. They contain the password hash: never pass them to
      a component, never return them from a Server Action.
   2. The "getMy..." / "getRecent..." fetchers of the Sécurité page: they call
      requireAdmin() themselves and return plain DTOs (dates as ISO strings).
   ========================================================================== */

/* --------------------------------------------------------------------------
   1. Internal records for the auth checks
   -------------------------------------------------------------------------- */

/** ⚠ Server-only record: contains the password hash and the encrypted 2FA secret. */
export type AdminAuthRecord = {
  id: number;
  email: string;
  name: string;
  passwordHash: string;
  totpEnabled: boolean;
  /** Encrypted with lib/auth/totp.ts (set during the 2FA setup, even before it is enabled). */
  totpSecret: string | null;
  failedAttempts: number;
  lockedUntil: Date | null;
  lastLoginAt: Date | null;
};

const AUTH_FIELDS = [
  "id",
  "email",
  "name",
  "passwordHash",
  "totpEnabled",
  "totpSecret",
  "failedAttempts",
  "lockedUntil",
  "lastLoginAt",
] as const;

/** The account for this e-mail (case-insensitive: e-mails are stored in lower case). */
export async function getAdminAuthByEmail(email: string): Promise<AdminAuthRecord | null> {
  const normalized = email.trim().toLowerCase();
  if (!normalized) return null;
  return db.orm.public.AdminUser.select(...AUTH_FIELDS)
    .where((u) => u.email.eq(normalized))
    .first();
}

export async function getAdminAuthById(id: number): Promise<AdminAuthRecord | null> {
  if (!Number.isInteger(id) || id <= 0) return null;
  return db.orm.public.AdminUser.select(...AUTH_FIELDS)
    .where((u) => u.id.eq(id))
    .first();
}

/* --------------------------------------------------------------------------
   2. The Sécurité page
   -------------------------------------------------------------------------- */

export type SecurityOverviewDTO = {
  name: string;
  email: string;
  totpEnabled: boolean;
  /** A 2FA secret was generated but not confirmed with a code yet. */
  totpSetupPending: boolean;
  passwordChangedAt: string | null;
  lastLoginAt: string | null;
  accountCreatedAt: string;
};

export async function getMySecurityOverview(): Promise<SecurityOverviewDTO> {
  const admin = await requireAdmin();
  const row = await db.orm.public.AdminUser.select(
    "name",
    "email",
    "totpEnabled",
    "totpSecret",
    "passwordChangedAt",
    "lastLoginAt",
    "createdAt",
  )
    .where((u) => u.id.eq(admin.id))
    .first();
  if (!row) throw new Error("Admin account not found.");
  return {
    name: row.name,
    email: row.email,
    totpEnabled: row.totpEnabled,
    totpSetupPending: !row.totpEnabled && row.totpSecret !== null,
    passwordChangedAt: row.passwordChangedAt?.toISOString() ?? null,
    lastLoginAt: row.lastLoginAt?.toISOString() ?? null,
    accountCreatedAt: row.createdAt.toISOString(),
  };
}

/** What the admin needs to add the site to an authenticator app (only during the setup). */
export type TotpEnrollmentDTO = {
  /** QR code as an SVG string generated by us (render with dangerouslySetInnerHTML). */
  qrCodeSvg: string;
  /** The same secret, grouped by 4 characters, for typing it by hand. */
  manualKey: string;
};

/** null when 2FA is already enabled or no setup was started. */
export async function getMyTotpEnrollment(): Promise<TotpEnrollmentDTO | null> {
  const admin = await requireAdmin();
  const row = await db.orm.public.AdminUser.select("email", "totpEnabled", "totpSecret")
    .where((u) => u.id.eq(admin.id))
    .first();
  if (!row || row.totpEnabled || !row.totpSecret) return null;

  const secret = decryptTotpSecret(row.totpSecret);
  if (!secret) return null; // unreadable (AUTH_SECRET changed): the admin can restart the setup
  return {
    qrCodeSvg: await totpQrCodeSvg(totpUri(secret, row.email)),
    manualKey: formatTotpSecret(secret),
  };
}

export type AdminSessionDTO = {
  /** sha256 of the cookie token (NOT the token itself: it cannot be used to log in). */
  id: string;
  isCurrent: boolean;
  /** Password OK but the 2FA code was not typed (yet). */
  isPending2fa: boolean;
  /** "Chrome · macOS" */
  device: string;
  userAgent: string | null;
  createdAt: string;
  lastSeenAt: string;
  expiresAt: string;
};

/** The open (not expired, not idle for 2 hours) sessions of the logged-in admin, most recent activity first. */
export async function getMyActiveSessions(): Promise<AdminSessionDTO[]> {
  const admin = await requireAdmin();
  const currentId = await getCurrentSessionId();
  const now = new Date();
  const idleSince = new Date(now.getTime() - SESSION_IDLE_TIMEOUT_MS);
  const rows = await db.orm.public.AdminSession.where((s) => s.adminId.eq(admin.id))
    .where((s) => s.expiresAt.gt(now))
    .where((s) => s.lastSeenAt.gte(idleSince))
    .orderBy([(s) => s.lastSeenAt.desc(), (s) => s.createdAt.desc()])
    .limit(50)
    .all();
  return rows.map((row) => ({
    id: row.id,
    isCurrent: row.id === currentId,
    isPending2fa: row.pending2fa,
    device: describeUserAgent(row.userAgent),
    userAgent: row.userAgent,
    createdAt: row.createdAt.toISOString(),
    lastSeenAt: row.lastSeenAt.toISOString(),
    expiresAt: row.expiresAt.toISOString(),
  }));
}

export type LoginAttemptDTO = {
  id: number;
  email: string;
  success: boolean;
  /** See LOGIN_REASONS in lib/auth/login-throttle.ts */
  reason: string | null;
  createdAt: string;
};

/** The latest login attempts on the admin area (all e-mails, known or not). */
export async function getRecentLoginAttempts(limit = 20): Promise<LoginAttemptDTO[]> {
  await requireAdmin();
  const rows = await db.orm.public.LoginAttempt.select("id", "email", "success", "reason", "createdAt")
    .orderBy([(a) => a.createdAt.desc(), (a) => a.id.desc()])
    .limit(clampLimit(limit))
    .all();
  return rows.map((row) => ({
    id: row.id,
    email: row.email,
    success: row.success,
    reason: row.reason,
    createdAt: row.createdAt.toISOString(),
  }));
}

