/* --------------------------------------------------------------------------
   Helpers
   -------------------------------------------------------------------------- */

function clampLimit(limit: number) {
  return Number.isFinite(limit) ? Math.min(200, Math.max(1, Math.trunc(limit))) : 20;
}

/** The first pattern that matches wins (order matters: Edge also says "Chrome", Chrome also says "Safari"). */
const BROWSERS: [RegExp, string][] = [
  [/Edg(e|A|iOS)?\//, "Edge"],
  [/OPR\/|Opera/, "Opera"],
  [/SamsungBrowser\//, "Samsung Internet"],
  [/Firefox\/|FxiOS\//, "Firefox"],
  [/Chrome\/|CriOS\//, "Chrome"],
  [/Safari\//, "Safari"],
  [/^curl\//i, "curl"],
];

const SYSTEMS: [RegExp, string][] = [
  [/iPhone/, "iPhone"],
  [/iPad/, "iPad"],
  [/Android/, "Android"],
  [/Windows/, "Windows"],
  [/Macintosh|Mac OS X/, "macOS"],
  [/CrOS/, "ChromeOS"],
  [/Linux/, "Linux"],
];

/** "Mozilla/5.0 (Macintosh; ...) Chrome/142..." → "Chrome · macOS" */
function describeUserAgent(userAgent: string | null): string {
  if (!userAgent) return "Appareil inconnu";
  const browser = BROWSERS.find(([pattern]) => pattern.test(userAgent))?.[1] ?? "Navigateur";
  const system = SYSTEMS.find(([pattern]) => pattern.test(userAgent))?.[1];
  return system ? `${browser} · ${system}` : browser;
}
